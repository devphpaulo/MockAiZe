const assert = require('node:assert/strict');
require('../mockaize/web/return-models.js');
const R = globalThis.ReturnModels;
const legacy = {outputTemplate:'<Ret><Value>old</Value></Ret>',outputGroup:'group',rulesByMode:{new:{keep:1},return:{value:{generator:{type:'literal',value:'one'}}}},presenceByMode:{new:{},return:{}},filenameByMode:{new:{type:'literal',value:'new'},return:{type:'literal',value:'original'}},outputNotesByMode:{new:{},return:{line:'original note'}},headersByMode:{new:[],return:['header']}};
const draft = R.ensure(structuredClone(legacy));
assert.equal(R.current(draft).outputXml, legacy.outputTemplate);
assert.deepEqual(draft.rulesByMode, legacy.rulesByMode);
const first = draft.activeReturnId;
R.add(draft, 'Segundo', 'second');
assert.equal(draft.outputTemplate, '');
assert.deepEqual(draft.rulesByMode.return, {});
draft.outputTemplate = '<Second/>';
draft.rulesByMode.return.field = {generator:{type:'literal',value:'two'}};
const beforeSave = JSON.stringify(draft);
const saved = R.forSave(draft);
assert.equal(JSON.stringify(draft), beforeSave, 'serialization must not dirty the editor');
assert.equal(saved[1].outputXml, '<Second/>');
R.capture(draft); R.activate(draft, first);
assert.equal(draft.outputTemplate, legacy.outputTemplate);
assert.deepEqual(draft.rulesByMode.new, legacy.rulesByMode.new);
R.rename(draft, first, 'Principal');
assert.throws(() => R.rename(draft, 'second', 'Principal'), /Já existe/);
const reopened = R.ensure({...structuredClone(draft),returnModels:saved});
R.activate(reopened, 'second');
assert.equal(reopened.rulesByMode.return.field.generator.value, 'two');
assert.equal(R.selected(reopened).length, 2);
R.current(reopened).selected = false;
assert.equal(R.selected(reopened).length, 1);
R.remove(reopened, 'second');
assert.equal(reopened.activeReturnId, first);
assert.throws(() => R.remove(reopened, first), /pelo menos/);
console.log('Return models: migration, isolation, selection, rename, deletion and restoration OK.');
